function [x nx sp dp dt] = chestnutparam(a,b,p,t,o)
% a = 1/2; b does not matter

th = pi/2; % change this later... need to rederive derivatives...

r = @(t,p)  [(a+sin(t/2).*cos(th*(t/(2*pi)-1/2))).*cos(p);...
             (a+sin(t/2).*cos(th*(t/(2*pi)-1/2))).*sin(p);...
             sin(t/2).*sin(th*(t/(2*pi)-1/2))]; % t,p rows
rt = @(t,p) [(1/2*cos(t/2).*cos(th*(t/(2*pi)-1/2)) - th/(2*pi)*sin(t/2).*sin(th*(t/(2*pi)-1/2))).*cos(p); ...
             (1/2*cos(t/2).*cos(th*(t/(2*pi)-1/2)) - th/(2*pi)*sin(t/2).*sin(th*(t/(2*pi)-1/2))).*sin(p);...
             1/2*cos(t/2).*sin(th*(t/(2*pi)-1/2)) + th/(2*pi)*sin(t/2).*cos(th*(t/(2*pi)-1/2))]; 
rp = @(t,p) [-(a+sin(t/2).*cos(th*(t/(2*pi)-1/2))).*sin(p);...
             (a+sin(t/2).*cos(th*(t/(2*pi)-1/2))).*cos(p);...
             0*p];

x = r(t,p);
rts = rt(t,p); rps = rp(t,p);
dt = sqrt(sum(rts.^2,1));
dp = sqrt(sum(rps.^2,1));    % could reuse this data
nx =  cross(rps, rts);       % outward normal
sp = sqrt(sum(nx.^2,1)); % speeds
nx = nx.*repmat(1./sp, [3 1]);