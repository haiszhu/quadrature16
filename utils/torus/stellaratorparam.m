function x = stellaratorparam(t,p)
% new torus

r = @(t,p)  0.17*[cos(t).*cos(2*p-t);sin(t).*cos(2*p-t);sin(2*p-t)]...
           +0.11*[cos(t).*cos(2*p);sin(t).*cos(2*p);sin(2*p)]...
           +   1*[cos(t).*cos(p);sin(t).*cos(p);sin(p)]...
           + 4.5*[cos(t);sin(t);zeros(size(t))]...
           -0.25*[cos(t).*cos(p);sin(t).*cos(p);-sin(p)]...
           +0.07*[cos(t).*cos(p+t);sin(t).*cos(p+t);sin(p+t)]...
           -0.45*[cos(t).*cos(-p+t);sin(t).*cos(-p+t);sin(-p+t)];
x = r(t,p);

end